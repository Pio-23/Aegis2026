#!/usr/bin/env python3
"""Look up exact original XYZ measurements by direction/height in AEGIS replay.

Works on a full_point_geometry.npz generated by aegis_lidar_scene.py.
This is NOT a safety clearance computation. No motors or AEGIS processes touched.

Example:
  python3 aegis_query_geometry.py /tmp/aegis_scene/full_point_geometry.npz \
      --angle 0 --half-width 2 --layer low
"""
import argparse
import json
import numpy as np
from aegis_lidar_scene import query_sector


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('geometry',help='path to full_point_geometry.npz')
    p.add_argument('--angle',type=float,required=True,help='Direction: 0 FRONT, +90 LEFT, -90 RIGHT')
    p.add_argument('--half-width',type=float,default=2.0,help='Angular half-width in degrees')
    p.add_argument('--layer',choices=['floor_candidate','low','mid','high','overhead'],default='mid')
    a=p.parse_args()
    if not 0 < a.half_width <= 180:
        p.error('--half-width must be within (0,180]')
    with np.load(a.geometry) as npz:
        points=npz['points_xyz_intensity']
        floor_z=float(npz['floor_z_sensor_frame'])
    outcome=query_sector(points,floor_z,a.angle,a.half_width,a.layer)
    print(json.dumps({'direction_deg':a.angle,'angular_half_width_deg':a.half_width,
                      'layer':a.layer,'floor_estimate_sensor_z':floor_z,
                      'measurement':outcome},indent=2))

if __name__=='__main__':
    main()
